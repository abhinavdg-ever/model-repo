#!/usr/bin/env python3
"""Export the page taxonomy's L1s and their L2s for review-ui's Page Details entry.

    python training/taxonomy/export_review_taxonomy.py           # write the file
    python training/taxonomy/export_review_taxonomy.py --check   # exit 1 when it is stale

Reads ``core-pipeline/stages/lib/keyword-canon/page_taxonomy.json`` (label_space) and writes
``review-ui/frontend/src/pageTaxonomy.json``: the Page Type ground truth offers the L1s, Page
Subtype the L2s of the L1 picked, and Specialty the specialties (2026-10-26, user). review-ui is built on its own, so
it reads this copy rather than the pipeline's file. Also the Provider Credentials master list
(2026-10-27, user): the client's reference list (provider_credentials_reference.json, codable
and non-codable), then the extractor's (provider_credentials_canon.json), each once.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "core-pipeline" / "stages" / "lib" / "keyword-canon" / "page_taxonomy.json"
CANON = REPO / "core-pipeline" / "stages" / "lib" / "keyword-canon"
OUT = REPO / "review-ui" / "frontend" / "src" / "pageTaxonomy.json"


def credentials() -> list[str]:
    reference = json.loads((CANON / "provider_credentials_reference.json").read_text(encoding="utf-8"))
    extractor = json.loads((CANON / "provider_credentials_canon.json").read_text(encoding="utf-8"))
    names = [entry["credential"].strip() for entry in reference["codable"] + reference["non_codable"]]
    out: list[str] = []
    for name in [*names, *extractor["credentials"]]:
        if name and name not in out:
            out.append(name)
    return out


def build() -> str:
    space = json.loads(SOURCE.read_text(encoding="utf-8"))["label_space"]
    data = {
        "comment": "Generated by training/taxonomy/export_review_taxonomy.py from page_taxonomy.json and the provider credential lists; do not edit.",
        "L1": space["L1"],
        "L2": {l1: space["L2"].get(l1, []) for l1 in space["L1"]},
        "specialty": space["specialty"],
        "provider_credentials": credentials(),
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the file does not match the taxonomy")
    args = parser.parse_args()
    text = build()
    if args.check:
        stale = not OUT.is_file() or OUT.read_text(encoding="utf-8") != text
        print(f"{OUT.relative_to(REPO)} is stale" if stale else "up to date")
        return int(stale)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
