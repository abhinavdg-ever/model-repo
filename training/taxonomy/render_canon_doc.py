#!/usr/bin/env python3
"""Write the canon appendix of ``docs/APPROACH.md``: every canon the v29.2
approach relies on, rendered from the JSON files themselves so the document cannot
drift from them. Only the text between the ``canon:start`` / ``canon:end`` markers is
replaced; the approach above them is written by hand.

    python training/taxonomy/render_canon_doc.py            # rewrites the appendix
    python training/taxonomy/render_canon_doc.py --check    # exit 1 when it is stale

Sources (all in the repo; no page text in any of them):

* ``training/taxonomy/taxonomy.json`` — the v29.2 label space (L1 / L2 / L3,
  descriptions, specialty values, rules)
* ``training/taxonomy/rules/taxonomy_rules.json`` — the v29.2 rules (context rules,
  MECE rules, page_type_overrides, family_map, merges)
* ``training/taxonomy/rules/name_map.json`` — 23 Oct names to v29.2
* ``training/taxonomy/page_canon.json`` — the keyword canon (page types,
  lexicons, codeability)
* ``training/taxonomy/rules/specialty.json``, ``rules/sections.json`` — the specialty
  and section lexicons
* ``training/taxonomy/rules/encounter_canon.json`` — the encounter lexicon used to
  bootstrap the encounter labels
* ``core-pipeline/stages/lib/keyword-canon/encounter_canon.json`` and
  ``continuity_canon.json`` — what the pipeline runs today
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
TAX = REPO / "training" / "taxonomy"
CANON = REPO / "core-pipeline" / "stages" / "lib" / "keyword-canon"
OUT = REPO / "docs" / "APPROACH.md"
START, END = "<!-- canon:start (generated by training/taxonomy/render_canon_doc.py; do not edit) -->", "<!-- canon:end -->"


def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def cell(value: Any) -> str:
    """One table cell: lists joined, pipes escaped, new lines flattened."""
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        value = ", ".join(cell(v) for v in value)
    elif isinstance(value, dict):
        value = "; ".join(f"{k}: {cell(v)}" for k, v in value.items() if not str(k).startswith("_"))
    return " ".join(str(value).split()).replace("|", "\\|")


def table(header: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return out + [""]


def comments(d: dict) -> list[str]:
    """The ``_comment*`` notes of a JSON object, as quoted paragraphs."""
    return [f"> {cell(v)}\n" for k, v in d.items() if str(k).startswith("_comment") and isinstance(v, str)]


def fields(d: dict) -> list[str]:
    """The non-comment fields of a JSON object, one bullet each."""
    return [f"* **{k}**: {cell(v)}" for k, v in d.items() if not str(k).startswith("_")]


# --- Sections ---------------------------------------------------------------------


def label_space(space: dict) -> list[str]:
    out = ["## A. The v29.2 label space", "",
           f"Version **{space['version']}**. Counts: " + ", ".join(f"{k} {v}" for k, v in space["counts"].items()) + ".",
           ""]
    out += ["### A.1 Rules", ""] + fields(space["rules"]) + [""]
    out += ["### A.2 L1", ""]
    out += table(["L1", "Description"], [[x["name"], x.get("description", "")] for x in space["L1"]])
    out += ["### A.3 L2 by L1", ""]
    for l1, l2s in space["L2"].items():
        if not l2s:
            continue
        out += [f"**{l1}**", ""]
        out += table(["L2", "Codeability", "Specialty", "Description"],
                     [[x["name"], x.get("codeability_tag") or x.get("codeability", ""), x.get("specialty", ""),
                       x.get("description", "")] for x in l2s])
    out += ["### A.4 L3 (Lab Report only)", ""]
    for parent, l3s in space["L3"].items():
        out += [f"**{parent}**", ""]
        out += table(["L3", "Specialty", "Description"],
                     [[x["name"], x.get("specialty", ""), x.get("description", "")] for x in l3s])
    out += ["### A.5 Specialty values", ""]
    out += table(["Specialty", "Description"], [[x["name"], x.get("description", "")] for x in space["specialty"]])
    return out


def name_map(m: dict) -> list[str]:
    out = ["## B. Renames from the 23 Oct v29 to v29.2", ""]
    for level in ("L1", "L2", "L3", "L3_extra"):
        if m.get(level):
            out += [f"**{level}**", ""] + table(["Old", "v29.2"], [[a, b] for a, b in m[level].items()])
    if m.get("L2_split"):
        out += ["**Split: a per-page decision, never automatic**", ""]
        out += table(["Old", "v29.2"], [[a, b] for a, b in m["L2_split"].items()])
    out += ["**New L1**: " + ", ".join(m.get("new_L1", [])), "", "**New L2**: " + ", ".join(m.get("new_L2", [])), ""]
    return out


def rules(r: dict) -> list[str]:
    out = ["## C. Context and MECE rules (v29.2 rules file)", "",
           "Context rules run after continuity: they decide a page's class from the document it sits in or from "
           "what the page is wholly about. MECE rules decide between two classes that a name alone cannot "
           "separate.", ""]
    out += comments({"_comment": r["context_rules"].get("_comment", "")})
    for name, rule in r["context_rules"].items():
        if name.startswith("_"):
            continue
        out += [f"### C.{name}", ""]
        if isinstance(rule, dict):
            out += comments(rule) + fields(rule) + [""]
        else:
            out += [cell(rule), ""]
    out += ["### MECE rules", ""] + comments({"_comment": r["mece_rules"].get("_comment", "")})
    for name, rule in r["mece_rules"].items():
        if name.startswith("_"):
            continue
        out += [f"#### {name}", ""]
        out += (comments(rule) + fields(rule) if isinstance(rule, dict) else [cell(rule)]) + [""]
    for key in ("consent_auth_side", "generic_leaf_rule", "lone_others_rule", "implied_specialty_rule",
                "l2_catch_all_rule", "no_L2_others", "flat_L1", "L2_from_page_type", "collapse_L3"):
        if key in r:
            out += [f"### {key}", ""] + (comments(r[key]) + fields(r[key]) if isinstance(r[key], dict)
                                         else [cell(r[key])]) + [""]
    out += ["### Other notes in the rules file", ""]
    out += [f"* **{k}**: {cell(v)}" for k, v in r.items() if k.startswith("_comment") or k == "note"] + [""]
    return out


def translation(r: dict) -> list[str]:
    out = ["## D. Canon page type → path (the conversion tables)", "",
           "How a keyword-canon page type became its path in page_canon.json (`canon_convert.py`). "
           "`page_type_overrides` names one page type; `family_map` covers a whole family. An override wins "
           "over the family.", ""]
    out += comments(r["page_type_overrides"])
    out += ["### D.1 page_type_overrides", ""]
    out += table(["Canon page type", "L1", "L2", "L3"],
                 [[k, v.get("L1", ""), v.get("L2", ""), v.get("L3", "")]
                  for k, v in sorted(r["page_type_overrides"].items()) if not k.startswith("_") and isinstance(v, dict)])
    out += ["### D.2 family_map", ""] + comments(r["family_map"])
    out += table(["Canon family", "L1", "L2", "L3"],
                 [[k, v.get("L1", ""), v.get("L2", ""), v.get("L3", "")]
                  for k, v in sorted(r["family_map"].items()) if not k.startswith("_") and isinstance(v, dict)])
    for key in ("L2_merge", "L3_merge"):
        out += [f"### D.{key}", ""] + comments(r[key])
        rows = []
        for parent, merges in r[key].items():
            if parent.startswith("_") or not isinstance(merges, dict):
                continue
            for a, b in merges.items():
                if isinstance(b, dict):
                    rows += [[f"{parent} > {a}", x, y] for x, y in b.items() if not x.startswith("_")]
                elif not a.startswith("_"):
                    rows.append([parent, a, b])
        out += table(["Under", "Old", "Merged into"], rows)
    return out


def page_canon(pc: dict) -> list[str]:
    out = ["## E. The keyword canon (page_canon.json)", "",
           f"Version {pc['version']} (taxonomy {pc['taxonomy']}). {cell(pc['status'])}", "",
           "Counts: " + ", ".join(f"{k} {v}" for k, v in pc["counts"].items()) + ".", "", "**How to match**", ""]
    out += [f"{n}. {cell(x)}" for n, x in enumerate(pc["how_to_match"], 1)] + [""]
    out += ["**Weights**: " + cell(pc["weights"]) + f". Title zone: the first {pc['title_zone_lines']} lines.", ""]
    out += ["**Codeability rules**: " + cell(pc["codeability_rules"]), ""]
    out += table(["Page type", "Family", "Path", "Codeability", "Specialty", "Title terms", "Body terms",
                  "Ambiguous terms"],
                 [[p["page_type"], p["family"], " > ".join(x for x in (p["path"].get("L1"), p["path"].get("L2"),
                                                                        p["path"].get("L3")) if x),
                   p["codeability"], p.get("specialty", ""), p["lexicon"].get("title_terms", []),
                   p["lexicon"].get("body_terms", []), p["lexicon"].get("ambiguous_terms", [])]
                  for p in sorted(pc["page_types"], key=lambda p: (p["family"], p["page_type"]))])
    return out


def specialty(s: dict) -> list[str]:
    out = ["## F. Specialty lexicon (specialty.json)", "", cell(s.get("note", "")), "",
           "**Matching**: " + cell(s["matching"]), ""]
    rows = []
    for name, spec in s["specialties"].items():
        if name.startswith("_") or not isinstance(spec, dict):
            continue
        rows.append([name, spec.get("header", []), spec.get("body", []), spec.get("_comment", "")])
    out += table(["Specialty", "Header / letterhead terms", "Body terms", "Note"], rows)
    out += ["**Page types that imply a specialty**", ""]
    out += table(["Page type", "Specialty"], [[k, v] for k, v in s["collapse_page_types"].items() if k != "comment"])
    return out


def sections(s: dict) -> list[str]:
    out = ["## G. Section lexicon (sections.json) — Progress Note L2", "", cell(s.get("note", "")), "",
           "**Matching**: " + cell(s["matching"]), ""]
    out += table(["Section", "Definition"], [[k, v] for k, v in s["sections"].items() if not k.startswith("_")])
    return out


def encounter_training(e: dict) -> list[str]:
    out = ["## H. Encounter lexicon used to label the training data (Training/processed/encounter_canon.json)", "",
           cell(e.get("note", "")), "", "**Classes**: " + ", ".join(e["classes"]), "",
           f"**Default when outpatient but the modality is unclear**: {e['default_when_outpatient_but_modality_unclear']}"
           f" — {cell(e.get('default_comment', ''))}", "", "**Matching**: " + cell(e["matching"]), ""]
    out += table(["Class", "Strong terms", "Weak terms", "Other"],
                 [[c, v.get("strong", []), v.get("weak", []),
                   {k: x for k, x in v.items() if k not in ("strong", "weak")}]
                  for c, v in e["lexicon"].items() if isinstance(v, dict)])
    out += ["**Document-type priors** (applied before the lexicon)", ""] + comments(e["document_type_priors"])
    out += table(["L1", "Prior"], [[k, v] for k, v in e["document_type_priors"].items() if not k.startswith("_")])
    out += ["**Patient-type field**", ""] + fields(e["patient_type_field"]) + [""]
    out += [f"* **{k}**: {cell(v)}" for k, v in e.items() if k.startswith("_comment")] + [""]
    return out


def encounter_pipeline(e: dict) -> list[str]:
    out = ["## I. The pipeline's encounter canon (core-pipeline keyword-canon/encounter_canon.json)", "",
           cell(e.get("note", "")), ""]
    out += ["**Settings**", ""] + table(["Key", "Stored as"], [[k, v] for k, v in e["settings"].items()])
    out += ["**Confidence by tier**: " + cell(e["confidence"]), "", "**Default**: " + cell(e["default"]), "",
            "**Applies to**: " + cell(e["applies_to"]), ""]
    out += ["**Tier 1: page types that decide the setting**", ""]
    out += table(["Page type", "Setting"], [[k, v] for k, v in e["tier1_page_types"].items() if not k.startswith("_")])
    for tier in ("tier2", "tier3"):
        out += [f"**{tier.capitalize()}: phrases**", ""]
        out += table(["Setting", "Phrases"], [[k, v] for k, v in e[tier].items() if not k.startswith("_")])
    out += ["**Context phrases**: " + cell(e.get("context", [])), "",
            "**Negatives** (phrases that cancel a match): " + cell(e.get("negatives", [])), "",
            "**Vote**: " + cell(e.get("vote", {})), ""]
    return out


def continuity(c: dict) -> list[str]:
    out = ["## J. The pipeline's continuity canon (keyword-canon/continuity_canon.json)", ""]
    for key, value in c.items():
        if isinstance(value, dict):
            out += [f"### {key}", ""] + comments(value) + fields(value) + [""]
        elif not key.startswith("_"):
            out += [f"* **{key}**: {cell(value)}", ""]
        else:
            out += [f"> {cell(value)}", ""]
    return out


def render() -> str:
    lines = ["# Appendix: the canon, taxonomy v29.2", "",
             "Rendered from the JSON files by `training/taxonomy/render_canon_doc.py`; run it after any canon "
             "change.", "",
             "Contents: A. label space · B. renames · C. context and MECE rules · D. canon conversion tables · "
             "E. keyword canon · F. specialty · G. sections · H. encounter (training) · I. encounter (pipeline) · "
             "J. continuity", ""]
    lines += label_space(load(TAX / "taxonomy.json"))
    lines += name_map(load(TAX / "rules" / "name_map.json"))
    rules_file = load(TAX / "rules" / "taxonomy_rules.json")
    lines += rules(rules_file)
    lines += translation(rules_file)
    lines += page_canon(load(TAX / "page_canon.json"))
    lines += specialty(load(TAX / "rules" / "specialty.json"))
    lines += sections(load(TAX / "rules" / "sections.json"))
    lines += encounter_training(load(TAX / "rules" / "encounter_canon.json"))
    lines += encounter_pipeline(load(CANON / "encounter_canon.json"))
    lines += continuity(load(CANON / "continuity_canon.json"))
    # One level down: the appendix sits under the approach's own headings.
    return "\n".join("#" + line if line.startswith("#") else line for line in lines).rstrip() + "\n"


def merged(document: str, appendix: str) -> str:
    """``document`` with the text between the markers replaced (markers appended when absent)."""
    block = f"{START}\n\n{appendix}\n{END}\n"
    if START in document and END in document:
        head, rest = document.split(START, 1)
        return head + block + rest.split(END, 1)[1].lstrip("\n")
    return document.rstrip() + "\n\n" + block


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is out of date")
    args = parser.parse_args(argv)
    current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
    text = merged(current, render())
    if args.check:
        if current != text:
            print(f"{OUT}: the canon appendix is stale: run python training/taxonomy/render_canon_doc.py")
            return 1
        print(f"{OUT}: the canon appendix is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote the canon appendix of {OUT} ({len(text.splitlines())} lines in all)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
